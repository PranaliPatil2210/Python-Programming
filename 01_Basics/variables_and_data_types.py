"""
Variables and Data Types in Python

This program demonstrates:
- Variables
- Built-in data types
- type() function
"""
a=1
print(a)
print(type(a))

b="gfd"
print(b)
print(type(b))

c=4.5
print(c)
print(type(c))

d=True
print(d)
print(type(d))

e=None
print(e)
print(type(e))

list1 = [4, 6, "Pranali", [2,6]] #mutable-can be changed
print(list1)
print(type(list1))

tuple1= ("hi", ("Pranali", 8, 0), "Sarthak", "Shreya") #immutable- can not be changed
print(tuple1)
print(type(tuple1))

dict1= {"name1": "Pranali", "name2":"Shreya", "name3":"Sarthak", "name1no.": 1, "name2no.": 2, "name3no.":3} #Key-value pair
print(dict1)
print(type(dict1))


